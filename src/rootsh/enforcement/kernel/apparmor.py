"""K2: AppArmor deny-inside-allow rules (design 09 §5).

Inside bwrap, Ubuntu stacks every child with `unpriv_bwrap`, which has no
`change_profile` rule, so a profile cannot be entered from inside the
sandbox [RUN]. K2 is therefore entered *outside*: the launcher runs bwrap
under `aa-exec -p rootsh-bwrap`, a copy of the system bwrap profile's
permissions whose exec transition stacks `rootsh-agent` (and
`unpriv_bwrap`, as the system profile does) onto everything bwrap starts.

`rootsh-agent` allows everything except: writes to rootsh's own code and
config, the OpenCode plugin dirs, git hooks and `.git/config`; any access to
rootsh's state and control socket; ptrace, D-Bus, new user namespaces,
mounts, capabilities, profile changes, and signals to processes outside the
agent's profile. Every deny is audited.

Loading needs root: `sudo rootsh install --system` writes PROFILE_PATH and
runs `apparmor_parser -r`. Tests only syntax-check (`-Q -K`, no load).
"""

from __future__ import annotations

import subprocess
from collections.abc import Sequence
from pathlib import Path

PROFILE_PATH = Path("/etc/apparmor.d/rootsh")
OUTER, AGENT = "rootsh-bwrap", "rootsh-agent"
PARSER, AA_EXEC = "/usr/sbin/apparmor_parser", "/usr/bin/aa-exec"
_FLAGS = "flags=(attach_disconnected,mediate_deleted)"


class AppArmorError(RuntimeError):
    pass


def _quote(path: Path, suffix: str = "") -> str:
    """`path` as a quoted profile pattern; `suffix` is appended unescaped
    (`/` for the directory itself, `/**` for everything beneath it)."""
    text = str(path)
    if any(c in text for c in '"\n\0') or not text.startswith("/"):
        raise AppArmorError(f"path unusable in a profile: {text!r}")
    # AppArmor globs: escape the characters that are glob syntax.
    for char in "*?[]{}^,":
        text = text.replace(char, "\\" + char)
    return f'"{text}{suffix}"'


def _ancestors(path: Path, stop: Path) -> list[Path]:
    """Directories above `path` up to (not including) `stop`, so renaming a
    parent cannot move a protected tree out from under its rules."""
    out: list[Path] = []
    for parent in path.parents:
        if parent == stop or parent == Path("/"):
            break
        out.append(parent)
    return out


def render(read_only: Sequence[Path], hidden: Sequence[Path], home: Path) -> str:
    """The profile file for both profiles. `read_only`: readable, never
    written; `hidden`: no access at all."""
    deny: list[str] = []
    # A path is matched as a file (no slash) and as a directory (slash).
    for paths, perms in ((read_only, "wl"), (hidden, "rwlk")):
        for path in paths:
            deny += [f"  audit deny {_quote(path, end)} {perms}," for end in ("", "/", "/**")]
    dirs = sorted({a for p in (*read_only, *hidden) for a in _ancestors(p, home)})
    deny += [f"  audit deny {_quote(d, '/')} w," for d in dirs]
    rules = "\n".join(deny)
    return f"""\
# rootsh K2 profiles (generated by rootsh; do not edit).
abi <abi/5.0>,
include <tunables/global>

profile {OUTER} {_FLAGS} {{
  allow capability,
  allow file rwlkm /{{**,}},
  allow network,
  allow unix,
  allow ptrace,
  allow signal,
  allow mqueue,
  allow io_uring,
  allow userns,
  allow mount,
  allow umount,
  allow pivot_root,
  allow dbus,
  allow pix /** -> &{AGENT}//&unpriv_bwrap,
}}

profile {AGENT} {_FLAGS} {{
  allow file rwlkm /{{**,}},
  allow ix /**,
  allow network,
  allow unix,
  allow mqueue,
  allow io_uring,
  allow signal peer={AGENT},
  allow signal peer={AGENT}//&unpriv_bwrap,
  audit deny signal (send) peer=unconfined,
  audit deny ptrace,
  audit deny dbus,
  audit deny userns,
  audit deny mount,
  audit deny umount,
  audit deny pivot_root,
  audit deny capability,
  audit deny change_profile,
  audit deny /**/.git/hooks/{{,**}} wl,
  audit deny /**/.git/config wl,
{rules}
}}
"""


def check(text: str) -> None:
    """Parse without loading (no root needed); raise on any error."""
    out = subprocess.run(  # noqa: S603 - fixed argv
        [PARSER, "-Q", "-K", "--skip-cache", "/dev/stdin"],
        input=text,
        capture_output=True,
        text=True,
        timeout=60,
        check=False,
    )
    if out.returncode != 0:
        raise AppArmorError(f"apparmor_parser rejected the profile: {out.stderr.strip()[:500]}")


def loaded(profile: str = OUTER) -> bool:
    """True when the kernel has `profile` (aa-exec refuses unknown ones)."""
    try:
        out = subprocess.run(  # noqa: S603 - fixed argv
            [AA_EXEC, "-p", profile, "--", "true"],
            capture_output=True,
            timeout=10,
            check=False,
        )
    except OSError:
        return False
    return out.returncode == 0


def current() -> str:
    """This process's AppArmor label, e.g. `rootsh-agent//&unpriv_bwrap (enforce)`."""
    try:
        return Path("/proc/self/attr/apparmor/current").read_text(encoding="utf-8").strip()
    except OSError:
        return ""
